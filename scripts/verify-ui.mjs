import { chromium, devices } from "@playwright/test";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
const base = process.env.TEST_BASE_URL || "http://localhost:3001";
await mkdir(".local", {recursive:true});
const browser = await chromium.launch();
const errors=[];
try {
  const desktop=await browser.newPage({viewport:{width:1440,height:1080}});
  desktop.on("pageerror",error=>errors.push(error.message));
  await desktop.goto(base);await desktop.getByRole("heading",{level:1}).waitFor();
  await desktop.screenshot({path:".local/desktop.png",fullPage:true});
  const context=await browser.newContext({...devices["iPhone 13"],recordVideo:{dir:".local/video",size:{width:390,height:844}}});
  const mobile=await context.newPage();mobile.on("pageerror",error=>errors.push(error.message));
  await mobile.goto(base);await mobile.getByRole("heading",{level:1}).waitFor();
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,"mobile has horizontal overflow");
  await mobile.screenshot({path:".local/mobile.png",fullPage:true});
  await mobile.getByRole("button",{name:"体验示例"}).click();
  await mobile.getByRole("heading",{name:"一份报告，如何让数据有据可循？"}).waitFor();
  assert.equal(await mobile.locator('.statement-tag').count(),0,'demo answers must have no classification badge');
  assert.doesNotMatch(await mobile.locator('.summary-box').innerText(),/分析推断|资料事实|示例说明/);
  await mobile.getByRole("button",{name:"查看来源 1 的证据"}).last().click();
  await mobile.getByRole("dialog").waitFor();
  await mobile.screenshot({path:".local/source-sheet.png"});
  assert.equal(await mobile.getByRole("link",{name:"打开原文"}).getAttribute("href"),"https://example.org");
  await mobile.keyboard.press("Escape");
  await mobile.getByRole("dialog").waitFor({state:"detached"});
  await mobile.getByRole("button",{name:"开始新的研究"}).click();
  const field=mobile.getByRole("textbox",{name:"研究问题"});
  await field.fill("这是一条用于失败重试的测试问题");
  let count=0;await mobile.route("**/api/analyze",route=>{count++;return route.fulfill({status:504,contentType:"application/json",body:JSON.stringify({error:{code:"TIMEOUT",message:"测试超时，请重试。"}})});});
  await mobile.getByRole("button",{name:"开始分析"}).click();
  await mobile.getByRole("alert").filter({hasText:"测试超时，请重试。"}).waitFor();
  assert.equal(await field.inputValue(),"这是一条用于失败重试的测试问题");
  await mobile.getByRole("button",{name:"重新分析"}).click();
  await mobile.getByRole("alert").filter({hasText:"测试超时，请重试。"}).waitFor();assert.equal(count,2);
  await mobile.unroute("**/api/analyze");
  const response=await mobile.request.post(`${base}/api/analyze`,{data:{idea:"短"}});assert.equal(response.status(),400);
  await mobile.setViewportSize({width:320,height:740});
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,"320px overflow");
  await context.close();
  assert.deepEqual(errors,[]);
  console.log("UI passed: desktop, 390px/320px mobile, demo citation, source link, Escape close, retry preserving input, invalid input API, no runtime errors.");
} finally {await browser.close();}
